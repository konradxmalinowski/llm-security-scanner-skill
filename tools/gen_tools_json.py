#!/usr/bin/env python3
"""Generate platforms/generic/tools.json from the MCP server's own tool definitions.

The generic adapter needs OpenAI/Gemini-style function declarations for platforms with
tool calling but no skill or MCP support. Hand-writing them would guarantee drift from
the MCP server, so they are derived from it and committed. `tests/test_tools_json.py`
fails if the committed file no longer matches, which is what keeps them in step.
"""

from __future__ import annotations

import asyncio
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "platforms" / "generic" / "tools.json"

# MCP tool name -> the llm-scanner-skill subcommand that implements it. Emitted as
# "x-command" so an integrator knows what to shell out to for each declaration.
COMMANDS: dict[str, str] = {
    "inspect_llm_application": "llm-scanner-skill inspect <path>",
    "list_scan_categories": "llm-scanner-skill categories",
    "check_authorization": "llm-scanner-skill authorize --target <t> --target-type <ty>",
    "generate_scan_config": "llm-scanner-skill init-config --target <t> --target-type <ty>",
    "validate_scan_config": "llm-scanner-skill validate-config <path>",
    "scan_target": "llm-scanner-skill scan --target <t> --target-type <ty> [--authorized]",
    "summarize_findings": "llm-scanner-skill summarize <report.json>",
    "get_remediation_guidance": "llm-scanner-skill remediate <LLM0X>",
    "compare_scan_results": "llm-scanner-skill compare <before.json> <after.json>",
    "read_report_excerpt": "llm-scanner-skill summarize <report.json> --include-safe",
    "server_info": "llm-scanner-skill doctor",
}


async def _collect() -> list[dict[str, object]]:
    from llm_scanner_skill.mcp_server import build_server

    server = build_server()
    tools = await server.list_tools()
    out: list[dict[str, object]] = []
    for tool in sorted(tools, key=lambda t: t.name):
        out.append(
            {
                "type": "function",
                "function": {
                    "name": tool.name,
                    "description": (tool.description or "").strip(),
                    # mcp 2.x exposes `input_schema`; 1.x used `inputSchema`.
                    "parameters": getattr(tool, "input_schema", None)
                    or getattr(tool, "inputSchema", {}),
                },
                "x-command": COMMANDS.get(tool.name, ""),
            }
        )
    return out


def main() -> int:
    try:
        tools = asyncio.run(_collect())
    except RuntimeError as exc:
        print(f"Could not build the MCP server: {exc}", file=sys.stderr)
        print(
            "Install the extra:  uv pip install 'llm-security-scanner-skill[mcp]'", file=sys.stderr
        )
        return 1

    doc = {
        "$comment": (
            "GENERATED by tools/gen_tools_json.py from the MCP server's tool definitions. "
            "Do not edit by hand; run the generator. Each entry's x-command is the "
            "llm-scanner-skill subcommand that implements it."
        ),
        "schema_version": "1.0",
        "tools": tools,
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(doc, indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {len(tools)} tool declaration(s) to {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
